using CSharpFunctionalExtensions;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using Newtonsoft.Json.Serialization;
using System;
using System.Collections.Generic;
using System.Dynamic;
using System.Linq;
using System.Text;
using static KYS.Library.Helpers.FormattingHelper;

namespace KYS.EFCore.Library.DBContext.Partials
{
    /// <summary>
    /// In-memory representation of the changes made to a single tracked entity, collected by
    /// <see cref="ApplicationDbContext.SaveChangesWithAuditAsync"/> and converted to an <see cref="ActionLog"/>
    /// through <see cref="ToActionLog"/>.
    /// </summary>
    public class AuditEntry
    {
        /// <summary>
        /// Gets or sets the name of the audited entity (its CLR type name).
        /// </summary>
        public string TableName { get; set; }
        /// <summary>
        /// Gets or sets the name of the changed property for an <see cref="AuditAction.Update"/>.
        /// <br /><br />
        /// When several properties change, only the last one processed is kept.
        /// </summary>
        public string ColumnName { get; set; }
        /// <summary>
        /// Gets or sets the kind of change made to the entity.
        /// </summary>
        public AuditAction Action { get; set; }
        /// <summary>
        /// Gets or sets the identifier of the user who made the change.
        /// </summary>
        public Guid? UserId { get; set; }
        /// <summary>
        /// Gets the primary key values of the entity, keyed by property name.
        /// </summary>
        public Dictionary<string, object> KeyValues { get; } = new Dictionary<string, object>();
        /// <summary>
        /// Gets the original property values (for deletions and updates), keyed by property name.
        /// </summary>
        public Dictionary<string, object> OldValues { get; } = new Dictionary<string, object>();
        /// <summary>
        /// Gets the current property values (for insertions and updates), keyed by property name.
        /// </summary>
        public Dictionary<string, object> NewValues { get; } = new Dictionary<string, object>();
        /// <summary>
        /// Gets the properties whose values are generated by the database and are only known after saving.
        /// </summary>
        public List<PropertyEntry> TemporaryProperties { get; } = new List<PropertyEntry>();
        /// <summary>
        /// Gets a value indicating whether the entry has properties that must be completed after saving.
        /// </summary>
        public bool HasTemporaryProperties => TemporaryProperties.Count > 0;

        /// <summary>
        /// Merge settings used to combine <see cref="KeyValues"/> with <see cref="NewValues"/> or <see cref="OldValues"/>.
        /// </summary>
        private static readonly JsonMergeSettings _mergeSettings = new JsonMergeSettings
        {
            MergeArrayHandling = MergeArrayHandling.Union
        };

        /// <summary>
        /// Serializer settings that keep property names unchanged.
        /// </summary>
        private static readonly JsonSerializerSettings _defaultJsonSerializerSettings = new JsonSerializerSettings
        {
            ContractResolver = new DefaultContractResolver
            {
                NamingStrategy = new DefaultNamingStrategy()
            }
        };

        /// <summary>
        /// Serializer settings that convert property and dictionary keys to snake_case.
        /// </summary>
        private static readonly JsonSerializerSettings _snakeCaseJsonSerializerSettings = new JsonSerializerSettings
        {
            ContractResolver = new DefaultContractResolver
            {
                NamingStrategy = new SnakeCaseNamingStrategy { ProcessDictionaryKeys = true }
            }
        };

        /// <summary>
        /// Converts this audit entry to an <see cref="ActionLog"/>.
        /// </summary>
        /// <param name="formatting">
        /// The naming convention applied to <see cref="ActionLog.ReferenceTable"/> and <see cref="ActionLog.ColumnName"/>.
        /// When it is <see cref="KYS.Library.Helpers.FormattingHelper.Formatting.SnakeCase"/>, the keys of
        /// <see cref="ActionLog.RecordValue"/> are converted to snake_case as well.
        /// <see langword="null"/> keeps the original names.
        /// </param>
        /// <returns>
        /// A successful <see cref="Result{T}"/> containing the <see cref="ActionLog"/>, or a failed result
        /// with an error message when the table or column name could not be formatted.
        /// </returns>
        /// <remarks>
        /// <list type="bullet">
        ///     <item><see cref="AuditAction.Insert"/>: <see cref="ActionLog.RecordValue"/> holds the key and new values as JSON.</item>
        ///     <item><see cref="AuditAction.Update"/>: <see cref="ActionLog.ColumnOldValue"/> and <see cref="ActionLog.ColumnNewValue"/> hold the values of <see cref="ColumnName"/>.</item>
        ///     <item><see cref="AuditAction.Delete"/>: <see cref="ActionLog.RecordValue"/> holds the key and original values as JSON.</item>
        /// </list>
        /// <see cref="ActionLog.ReferenceId"/> is taken from the first entry of <see cref="KeyValues"/>.
        /// </remarks>
        /// <exception cref="InvalidOperationException"><see cref="Action"/> is <see cref="AuditAction.Update"/> and <see cref="ColumnName"/> has no matching entry in <see cref="OldValues"/> or <see cref="NewValues"/>.</exception>
        public Result<ActionLog> ToActionLog(KYS.Library.Helpers.FormattingHelper.Formatting? formatting = null)
        {
            string formattedTableName = TableName;
            string formattedColumnName = ColumnName;

            if (formatting != null)
            {
                var tableNameResult = TableName.Convert(formatting.Value);
                if (tableNameResult.IsFailure)
                    return Result.Failure<ActionLog>($"Failed to convert table name '{TableName}' with error: {tableNameResult.Error}");

                var columnNameResult = ColumnName.Convert(formatting.Value);
                if (columnNameResult.IsFailure)
                    return Result.Failure<ActionLog>($"Failed to convert column name '{ColumnName}' with error: {columnNameResult.Error}");

                formattedTableName = tableNameResult.Value;
                formattedColumnName = columnNameResult.Value;
            }

            var auditLog = new ActionLog
            {
                ReferenceId = KeyValues.FirstOrDefault().Value.ToString(),
                ReferenceTable = formattedTableName,
                ColumnName = formattedColumnName,
                ActionType = Action,
                CreatedDate = DateTime.UtcNow,
                CreatedBy = UserId
            };

            JObject recordValueJObj;
            JsonSerializerSettings jsonSerializerSettings = formatting switch
            {
                KYS.Library.Helpers.FormattingHelper.Formatting.SnakeCase => _snakeCaseJsonSerializerSettings,
                _ => _defaultJsonSerializerSettings
            };

            switch (Action)
            {
                case AuditAction.Insert:
                    recordValueJObj = JObject.FromObject(KeyValues);
                    recordValueJObj.Merge(JObject.FromObject(NewValues), _mergeSettings);

                    auditLog.RecordValue = JsonConvert.SerializeObject(recordValueJObj.ToObject<ExpandoObject>(),
                        jsonSerializerSettings);

                    break;

                case AuditAction.Update:
                    auditLog.ColumnOldValue = OldValues.First(x => x.Key == ColumnName)
                        .Value
                        .ToString();
                    auditLog.ColumnNewValue = NewValues.First(x => x.Key == ColumnName)
                        .Value
                        .ToString();

                    break;

                case AuditAction.Delete:
                    recordValueJObj = JObject.FromObject(KeyValues);
                    recordValueJObj.Merge(JObject.FromObject(OldValues), _mergeSettings);

                    auditLog.RecordValue = JsonConvert.SerializeObject(recordValueJObj.ToObject<ExpandoObject>(),
                        jsonSerializerSettings);

                    break;
            }

            return auditLog;
        }
    }
}
