using KYS.EFCore.Library.DBContext.Partials;
using KYS.Library.Extensions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using static KYS.Library.Helpers.FormattingHelper;

namespace KYS.EFCore.Library.DBContext
{
    public partial class ApplicationDbContext
    {
        /// <summary>
        /// Saves all changes made in this context to the database and writes an <see cref="DBContext.ActionLog"/>
        /// record for every added, modified or deleted entity.
        /// </summary>
        /// <param name="actionBy">The identifier of the user making the change, stored in <see cref="DBContext.ActionLog.CreatedBy"/>.</param>
        /// <param name="formatting">
        /// The naming convention applied to <see cref="DBContext.ActionLog.ReferenceTable"/> and <see cref="DBContext.ActionLog.ColumnName"/>.
        /// When it is <see cref="KYS.Library.Helpers.FormattingHelper.Formatting.SnakeCase"/>, the keys of
        /// <see cref="DBContext.ActionLog.RecordValue"/> are converted to snake_case as well.
        /// <see langword="null"/> keeps the original names.
        /// </param>
        /// <returns>
        /// The number of state entries written to the database by the main save,
        /// including the audit records that could be created before saving.
        /// </returns>
        /// <remarks>
        /// <list type="number">
        ///     <item>Changes are detected and an <see cref="AuditEntry"/> is built for each tracked entity
        ///     (excluding <see cref="DBContext.ActionLog"/> entities and detached or unchanged entries).</item>
        ///     <item>Audit records whose values are already known are added, then the changes are saved.</item>
        ///     <item>Audit records for entities with database-generated values (e.g. identity keys) are completed
        ///     with the generated values and saved with a second <see cref="DbContext.SaveChangesAsync(System.Threading.CancellationToken)"/> call.</item>
        /// </list>
        /// The two saves are not wrapped in a transaction by this method. Use an <see cref="IUnitOfWork"/>
        /// (or an explicit transaction) if both must succeed or fail together.
        /// </remarks>
        /// <exception cref="InvalidOperationException">An audit entry could not be converted to an <see cref="DBContext.ActionLog"/>, for example because a name could not be formatted.</exception>
        public async Task<int> SaveChangesWithAuditAsync(Guid? actionBy = null,
            Formatting? formatting = null)
        {
            ChangeTracker.DetectChanges();
            var auditEntries = OnBeforeSaveChanges(actionBy, formatting);
            var result = await base.SaveChangesAsync();
            await OnAfterSaveChangesAsync(auditEntries, formatting);
            return result;
        }

        /// <summary>
        /// Builds an <see cref="AuditEntry"/> for each auditable tracked entity and adds an <see cref="DBContext.ActionLog"/>
        /// for every entry that has no temporary (database-generated) values.
        /// </summary>
        /// <param name="actionBy">The identifier of the user making the change.</param>
        /// <param name="formatting">The naming convention applied to the audit record.</param>
        /// <returns>The audit entries that still contain temporary values and must be completed after saving.</returns>
        /// <exception cref="InvalidOperationException">An audit entry could not be converted to an <see cref="DBContext.ActionLog"/>.</exception>
        private List<AuditEntry> OnBeforeSaveChanges(Guid? actionBy, Formatting? formatting)
        {
            var auditEntries = new List<AuditEntry>();
            foreach (var entry in ChangeTracker.Entries())
            {
                if (!ShouldAuditEntry(entry))
                    continue;

                var auditEntry = new AuditEntry
                {
                    TableName = entry.Entity.GetType().Name,
                    UserId = actionBy
                };
                auditEntries.Add(auditEntry);

                foreach (var property in entry.Properties)
                {
                    ProcessProperty(entry, property, auditEntry);
                }
            }

            var noTempPropAuditEntries = auditEntries.Where(e => !e.HasTemporaryProperties).ToList();
            foreach (var auditEntry in noTempPropAuditEntries)
            {
                var result = auditEntry.ToActionLog(formatting);
                if (result.IsFailure)
                    throw new InvalidOperationException(result.Error);

                ActionLog.Add(result.Value);
            }

            return auditEntries.Where(e => e.HasTemporaryProperties).ToList();
        }

        /// <summary>
        /// Completes the pending audit entries with the values generated by the database,
        /// adds the corresponding <see cref="DBContext.ActionLog"/> records and saves them.
        /// </summary>
        /// <param name="auditEntries">The audit entries returned by <see cref="OnBeforeSaveChanges"/>.</param>
        /// <param name="formatting">The naming convention applied to the audit record.</param>
        /// <exception cref="InvalidOperationException">An audit entry could not be converted to an <see cref="DBContext.ActionLog"/>.</exception>
        private async Task OnAfterSaveChangesAsync(List<AuditEntry> auditEntries, Formatting? formatting)
        {
            if (auditEntries.IsNullOrEmpty())
                return;

            foreach (var auditEntry in auditEntries)
            {
                foreach (var prop in auditEntry.TemporaryProperties)
                {
                    if (prop.Metadata.IsPrimaryKey())
                    {
                        auditEntry.KeyValues[prop.Metadata.Name] = prop.CurrentValue;
                    }
                    else
                    {
                        auditEntry.NewValues[prop.Metadata.Name] = prop.CurrentValue;
                    }
                }

                var result = auditEntry.ToActionLog(formatting);
                if (result.IsFailure)
                    throw new InvalidOperationException(result.Error);

                ActionLog.Add(result.Value);
            }

            await base.SaveChangesAsync();
        }

        /// <summary>
        /// Determines whether a tracked entry should be audited.
        /// </summary>
        /// <param name="entry">The tracked entry.</param>
        /// <returns>
        /// <see langword="false"/> for <see cref="DBContext.ActionLog"/> entities and for detached or unchanged entries;
        /// otherwise <see langword="true"/>.
        /// </returns>
        private static bool ShouldAuditEntry(EntityEntry entry)
            => !(entry.Entity is ActionLog
                || entry.State == EntityState.Detached
                || entry.State == EntityState.Unchanged);

        /// <summary>
        /// Records a single property of a tracked entry in the audit entry: as a temporary property
        /// (database-generated value), as a key value, or as an old/new value depending on the entity state.
        /// </summary>
        /// <param name="entry">The tracked entry that owns the property.</param>
        /// <param name="property">The property to record.</param>
        /// <param name="auditEntry">The audit entry being built.</param>
        private static void ProcessProperty(EntityEntry entry, PropertyEntry property, AuditEntry auditEntry)
        {
            // Treat database-generated properties as temporary. Some providers
            // (SQLite) may not mark non-PK store-generated columns as
            // PropertyEntry.IsTemporary; additionally treat properties with
            // ValueGenerated.OnAdd and no client value as temporary so the
            // post-save step can capture the generated value.
            var isStoreGeneratedOnAdd = property.Metadata.ValueGenerated == Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.OnAdd
                                         && property.CurrentValue == null;

            if (property.IsTemporary || isStoreGeneratedOnAdd)
            {
                auditEntry.TemporaryProperties.Add(property);
                return;
            }

            var propertyName = property.Metadata.Name;
            if (property.Metadata.IsPrimaryKey())
            {
                auditEntry.KeyValues[propertyName] = property.CurrentValue;
                return;
            }

            ApplyStateChange(entry, property, auditEntry, propertyName);
        }

        /// <summary>
        /// Sets the audit action and the old/new values of a non-key property based on the state of the entry.
        /// </summary>
        /// <param name="entry">The tracked entry that owns the property.</param>
        /// <param name="property">The property to record.</param>
        /// <param name="auditEntry">The audit entry being built.</param>
        /// <param name="propertyName">The name of the property.</param>
        /// <remarks>
        /// For modified entries, <see cref="AuditEntry.ColumnName"/> is overwritten by each changed property,
        /// so only the last changed property is reported in the resulting <see cref="DBContext.ActionLog"/>.
        /// </remarks>
        private static void ApplyStateChange(EntityEntry entry, PropertyEntry property, AuditEntry auditEntry, string propertyName)
        {
            switch (entry.State)
            {
                case EntityState.Added:
                    auditEntry.Action = AuditAction.Insert;
                    auditEntry.NewValues[propertyName] = property.CurrentValue;
                    break;

                case EntityState.Deleted:
                    auditEntry.Action = AuditAction.Delete;
                    auditEntry.OldValues[propertyName] = property.OriginalValue;
                    break;

                case EntityState.Modified:
                    auditEntry.Action = AuditAction.Update;
                    if (property.IsModified && !Equals(property.OriginalValue, property.CurrentValue))
                    {
                        auditEntry.ColumnName = propertyName;
                        auditEntry.OldValues[propertyName] = property.OriginalValue;
                        auditEntry.NewValues[propertyName] = property.CurrentValue;
                    }
                    break;
            }
        }
    }
}
